import { chromium } from 'playwright';
import path from 'path';
import { fileURLToPath } from 'url';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.resolve(__dirname, '../../../../site');
const url = 'file://' + SITE.split(String.fromCharCode(92)).join('/') + '/dev-dinos.html';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1024, height: 900 } });
const consoleErrors = [];
page.on('pageerror', err => consoleErrors.push(String(err)));
page.on('console', msg => { if (msg.type() === 'error') consoleErrors.push(msg.text()); });
const failed404 = [];
page.on('response', res => { if (res.status() === 404) failed404.push(res.url()); });
await page.goto(url, { waitUntil: 'load' });
await page.waitForTimeout(500);
const shot = path.resolve(__dirname, 'familles-tab.png');
await page.screenshot({ path: shot, fullPage: false });
console.log('Console errors:', consoleErrors.length ? consoleErrors : 'aucune');
console.log('404s:', failed404.length ? failed404 : 'aucun');
await browser.close();
